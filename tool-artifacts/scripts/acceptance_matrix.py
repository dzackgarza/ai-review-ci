"""Plan the acceptance workflow's shard matrix (.github/workflows/_acceptance.yml).

Usage: acceptance_matrix.py SHARDS_JSON

SHARDS_JSON maps each acceptance test file, as a path relative to tests/acceptance/, to
the number of shards it is split into. Run from the target repository root. Prints the
GitHub Actions matrix as ``matrix=<json>`` for $GITHUB_OUTPUT.

The mapping must name exactly the test files present: a file without a shard count
would never run, and a count without a file names a suite that no longer exists.
"""

import json
import sys
from pathlib import Path

SUITE = Path("tests/acceptance")
TEST_PATTERNS = ("test_*.sage", "*_test.sage", "test_*.py", "*_test.py")
# GitHub Actions' limit on jobs generated by one matrix.
MAX_JOBS = 256


def main(shards_json: str) -> int:
    shards = json.loads(shards_json)
    if not isinstance(shards, dict) or not all(isinstance(count, int) and not isinstance(count, bool) and count >= 1 for count in shards.values()):
        raise SystemExit(f"shards must map each tests/acceptance/ file to a positive shard count, got {shards_json}")
    present = {path.relative_to(SUITE).as_posix() for pattern in TEST_PATTERNS for path in SUITE.rglob(pattern)}
    if not present:
        raise SystemExit(f"no acceptance test files under {SUITE}/")
    unsharded = sorted(present - shards.keys())
    absent = sorted(shards.keys() - present)
    if unsharded or absent:
        raise SystemExit(f"shards must name exactly the files in {SUITE}/; without a shard count: {unsharded}; not present: {absent}")
    include = [
        {"file": file, "name": Path(file).with_suffix("").as_posix().replace("/", "."), "shard": shard, "shards": count}
        for file, count in sorted(shards.items())
        for shard in range(count)
    ]
    if len(include) > MAX_JOBS:
        raise SystemExit(f"{len(include)} shards exceed the {MAX_JOBS}-job matrix limit")
    print("matrix=" + json.dumps({"include": include}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
